// = , ==, ===

// These are the comparison operators in JavaScript. 
// They are used to compare two values and return a boolean value (true or false) based on the comparison.


// = (Assignment Operator)
// == (Equality Operator) Loose comparater
// === (Strict Equality Operator) Strict Comparison


console.log(10 == "10"); // losse comparison, value check or compare
console.log(10 === "10"); // strict comparison, value and both datatype check


console.log(3 == 4); 
console.log(4!== 4);